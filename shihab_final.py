def fit_pair(k, c):
    # temperature + Youden threshold if at least 10 positives and 10 negatives, else None
    if k.sum() == 0 or not (10 <= yv[k, c].sum() <= k.sum() - 10):
        return None
    t_ = fit_temperature(pr_val['logits'][k, c], yv[k, c])
    return t_, youden_thr(yv[k, c], 1 / (1 + np.exp(-pr_val['logits'][k, c] / t_)))

