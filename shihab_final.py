def blurred(x1):
    # realistic 'removed' content: a heavily blurred copy of the same X-ray (used by deletion, LIME and KernelSHAP)
    k = int(ISZ / 8) | 1
    return torch.stack([torch.from_numpy(cv2.GaussianBlur(c, (k, k), ISZ / 16)) for c in x1.detach().cpu().numpy()]).to(x1.device)

def to_nchw(f, nf):
    return f.permute(0, 3, 1, 2) if (f.ndim == 4 and f.shape[-1] == nf and f.shape[1] != nf) else f

def cams(net, x, cls, age=None, age_known=None, n_smooth=None, max_batch=None):
    # Grad-CAM and HiResCAM on each branch's last feature map, averaged over n_smooth noisy copies (copy 0 is clean)
    n_smooth = max(1, CFG['CAM_SMOOTH'] if n_smooth is None else n_smooth)
    max_batch = max_batch or CFG['CAM_MAX_BATCH']
    B = len(x)
    step = max(1, max_batch // n_smooth)
    if B > step:   # split into chunks so (images x noisy copies) with gradients fits in memory
        parts = [cams(net, x[i:i + step], cls[i:i + step], None if age is None else age[i:i + step],
                      None if age_known is None else age_known[i:i + step], n_smooth, max_batch) for i in range(0, B, step)]
        return {k_: np.concatenate([p_[0][k_] for p_ in parts]) for k_ in parts[0][0]}, np.concatenate([p_[1] for p_ in parts])
    if n_smooth > 1:
        noise = torch.randn((B, n_smooth) + tuple(x.shape[1:]), device=x.device) * 0.1; noise[:, 0] = 0
        x = (x[:, None] + noise).flatten(0, 1); cls = cls.repeat_interleave(n_smooth)
        age = age.repeat_interleave(n_smooth) if age is not None else None
        age_known = age_known.repeat_interleave(n_smooth) if age_known is not None else None
    net.eval(); net.zero_grad(set_to_none=True)
    out = net(x, age, age_known, return_maps=True)
    for m in out['maps']: m.retain_grad()
    out['logits'][torch.arange(len(x)), cls].sum().backward()
    res = {'gradcam': [], 'hirescam': []}
    for m, br in zip(out['maps'], net.branches):
        A, G = to_nchw(m.detach().float(), br.nf), to_nchw(m.grad.detach().float(), br.nf)
        res['gradcam'].append(F.relu((G.mean((2, 3), keepdim=True) * A).sum(1)))
        res['hirescam'].append(F.relu((G * A).sum(1)))
    w = out['gate'].detach().view(B, n_smooth, -1).mean(1)
    final = {}
    for k_, lst in res.items():
        ups = []
        for c in lst:
            c = c.view(B, n_smooth, *c.shape[1:]).mean(1)          # average the noisy copies
            c = F.interpolate(c[:, None], size=(ISZ, ISZ), mode='bilinear', align_corners=False)[:, 0]
            c = c / (c.flatten(1).max(1)[0][:, None, None] + 1e-8); ups.append(c)
        final[k_ + '_branches'] = torch.stack(ups, 1).cpu().numpy()
        final[k_ + '_fused'] = (torch.stack(ups, 1) * w[:, :, None, None]).sum(1).cpu().numpy()
    probs = torch.sigmoid(out['logits'].detach().view(B, n_smooth, -1)[:, 0]).cpu().numpy()
    return final, probs

