def augment(img, rng):
    h, w = img.shape
    sc, ar = rng.uniform(0.80, 1.0), rng.uniform(0.9, 1.1)
    ch, cw = min(h, int(h * math.sqrt(sc / ar))), min(w, int(w * math.sqrt(sc * ar)))
    y0, x0 = rng.integers(0, h - ch + 1), rng.integers(0, w - cw + 1)
    img = cv2.resize(img[y0:y0 + ch, x0:x0 + cw], (ISZ, ISZ), interpolation=cv2.INTER_AREA)
    M = cv2.getRotationMatrix2D((ISZ / 2, ISZ / 2), rng.uniform(-10, 10), rng.uniform(0.95, 1.05))
    M[:, 2] += rng.uniform(-0.04, 0.04, 2) * ISZ
    img = cv2.warpAffine(img, M, (ISZ, ISZ), borderMode=cv2.BORDER_REFLECT_101)   # no black borders
    f = img.astype(np.float32) / 255.0
    f = np.clip(f * rng.uniform(0.85, 1.15) + rng.uniform(-0.08, 0.08), 0, 1) ** rng.uniform(0.8, 1.25)
    if rng.random() < 0.2:
        f = np.clip(f + rng.normal(0, 0.02, f.shape).astype(np.float32), 0, 1)
    return f   # no horizontal flip: it would move the heart to the right side

def corrupt(f, kind, sev):
    if kind == 'noise':    return np.clip(f + np.random.normal(0, [0.03, 0.06, 0.10][sev], f.shape).astype(np.float32), 0, 1)
    if kind == 'blur':     return cv2.GaussianBlur(f, (0, 0), [1.0, 2.0, 3.0][sev])
    if kind == 'contrast': c = [0.75, 0.55, 0.35][sev]; return np.clip((f - f.mean()) * c + f.mean(), 0, 1)
    if kind == 'jpeg':
        ok, b = cv2.imencode('.jpg', (f * 255).astype(np.uint8), [cv2.IMWRITE_JPEG_QUALITY, [30, 15, 8][sev]])
        return cv2.imdecode(b, cv2.IMREAD_GRAYSCALE).astype(np.float32) / 255
    return f

