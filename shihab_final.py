pp = verify(np.stack([ped_idx[cand[:, 0]], ped_idx[cand[:, 1]]], 1)) if len(cand) else np.zeros((0, 2), int)
for i, j in pp: uf.u(i, j)
print(f'Pediatric near-duplicates: {len(cand)} pHash candidates -> {len(pp)} confirmed')
# across datasets (adult NIH vs pediatric)
cross = np.zeros((0, 2), int)
if CFG['PHASH_CROSS']:
    nih_idx = np.where(meta.source.values == 'NIH')[0]
    cand = near_dup_pairs(H[nih_idx], H[ped_idx], thr)
