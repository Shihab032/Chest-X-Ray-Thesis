"""## 9. Calibration and age-specific thresholds (validation only)
Per disease and per **age band** (adult 18+, child 6-17, child 0-5, child of unknown age): a temperature minimising NLL, then a threshold maximising Youden's J. Each disease is calibrated **only on the datasets that contain it** (Guangzhou images are used for Pneumonia only). Bands with fewer than 10 positives or negatives fall back: child band → all children → adult → pooled. An **image-level abnormal cut-off** is also fitted, so "abnormal" is no longer "any of 14 thresholds fired". All numbers are frozen **before** the test set is opened.
"""

