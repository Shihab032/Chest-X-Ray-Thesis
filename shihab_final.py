class Branch(nn.Module):
    def __init__(self, name, img_size):
        super().__init__()
        kw = {'img_size': img_size} if (img_size != 224 and any(k in name for k in ('swin', 'vit', 'eva'))) else {}
        self.net = timm.create_model(name, pretrained=False, num_classes=0, **kw)
        self.nf = self.net.num_features

    def forward(self, x):
        f = self.net.forward_features(x)
        return f, self.net.forward_head(f, pre_logits=True)


class AGFNet(nn.Module):
    def __init__(self, names, n_labels, proj, dropout, film, age_head, sub_head, logit_adj, prior_logit, tau, img_size):
        super().__init__()
        self.branches = nn.ModuleList([Branch(n, img_size) for n in names])
        self.projs = nn.ModuleList([nn.Sequential(nn.Linear(b.nf, proj), nn.LayerNorm(proj), nn.GELU()) for b in self.branches])
        K = len(names)
        self.gate = nn.Sequential(nn.Linear(proj * K, 256), nn.GELU(), nn.Linear(256, K)) if K > 1 else None
        self.age_head = nn.Linear(proj, 1) if age_head else None
        self.film = nn.Sequential(nn.Linear(1, 64), nn.GELU(), nn.Linear(64, 2 * proj)) if film else None
        self.head = nn.Sequential(nn.LayerNorm(proj), nn.Dropout(dropout), nn.Linear(proj, n_labels))
        self.sub_head = nn.Linear(proj, 2) if sub_head else None
        self.logit_adj, self.tau = logit_adj, tau
        self.register_buffer('prior_logit', torch.tensor(np.asarray(prior_logit), dtype=torch.float32))

    def forward(self, x, age=None, age_known=None, return_maps=False):
        maps, feats = [], []
        for b, pj in zip(self.branches, self.projs):
            f, p = b(x); maps.append(f); feats.append(pj(p))
        Fs = torch.stack(feats, 1)
        w = torch.softmax(self.gate(Fs.flatten(1)), -1) if self.gate is not None else torch.ones(Fs.shape[:2], device=x.device)
        z = (w.unsqueeze(-1) * Fs).sum(1)
        age_logit = self.age_head(z).squeeze(-1) if self.age_head is not None else None
        a = None
        if self.film is not None or self.logit_adj:
            a = torch.sigmoid(age_logit).detach() if age_logit is not None else torch.full((x.shape[0],), 0.5, device=x.device)
            if age is not None:
                a = torch.where(age_known > 0.5, age.float(), a)
        zc = z
        if self.film is not None:
            g, bb = self.film(a.unsqueeze(-1)).chunk(2, -1)
            zc = z * (1 + g) + bb
        logits = self.head(zc)
        if self.logit_adj:
            logits = logits + self.tau * ((1 - a)[:, None] * self.prior_logit[0] + a[:, None] * self.prior_logit[1])
        out = dict(logits=logits, age_logit=age_logit, gate=w, sub_logits=self.sub_head(zc) if self.sub_head is not None else None)
        if return_maps:
            out['maps'] = maps
        return out


