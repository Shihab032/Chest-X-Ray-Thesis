"""## 14b. Few-shot adaptation to a pediatric site
How much does a handful of labelled children improve the frozen model on a pediatric site? For each target test set and label, *k* positive and *k* negative **patients** form the support set; all other patients of that site form the query set (no patient in both).

* **Zero adaptation:** the frozen model's logit $\ell_0(x)$.
* **Linear probe:** logistic regression on the fused features *z* only (ignores the trained head).
* **Prior-anchored adapter (proposed, as in the FYDP):** $s(x)=\ell_0(x)+w^\top \tilde z(x)+b$ with an L2 penalty $\lambda\lVert w\rVert^2$. With $w=0$ it is exactly the frozen model. $\lambda$, including *no adaptation*, is chosen by 3-fold grouped CV on the support set only. Features are standardised with unlabelled target images.

Each *k* is repeated `FEWSHOT_REPS` times with different support patients. This is most informative for the `adult_only` experiment (adult model meets children).
"""

from sklearn.metrics import balanced_accuracy_score

def fit_adapter(Zs, l0, y, lam):
    Zt, l0t, yt = torch.tensor(Zs, dtype=torch.float32), torch.tensor(l0, dtype=torch.float32), torch.tensor(y, dtype=torch.float32)
    w = torch.zeros(Zt.shape[1], requires_grad=True); b0 = torch.zeros(1, requires_grad=True)
    opt = torch.optim.LBFGS([w, b0], lr=0.5, max_iter=100, line_search_fn='strong_wolfe')
    def clo():
        opt.zero_grad(); l = F.binary_cross_entropy_with_logits(l0t + Zt @ w + b0, yt) + lam * (w * w).sum(); l.backward(); return l
    opt.step(clo)
    return w.detach().numpy(), float(b0.item())

def bce_np(s, y):
    return float(F.binary_cross_entropy_with_logits(torch.tensor(s, dtype=torch.float32), torch.tensor(y, dtype=torch.float32)))

def choose_lam(Zs, l0, y, groups, grid=(0.01, 0.1, 1.0, 10.0)):
    if len(np.unique(groups)) < 6:
        return 1.0
    scores = {lam: [] for lam in grid}; scores[None] = []
    for tr_, va_ in GroupKFold(3).split(Zs, y, groups):
        if len(np.unique(y[tr_])) < 2: continue
        scores[None].append(bce_np(l0[va_], y[va_]))
        for lam in grid:
            w, b_ = fit_adapter(Zs[tr_], l0[tr_], y[tr_], lam); scores[lam].append(bce_np(l0[va_] + Zs[va_] @ w + b_, y[va_]))
    if not scores[None]:
        return 1.0
    return min(scores, key=lambda k_: np.mean(scores[k_]))      # None = keep the frozen model

