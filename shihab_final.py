"""## 13b. LIME and KernelSHAP (model-agnostic explanations)
Both explain one prediction by switching **superpixels** (SLIC regions) on and off and watching the class probability.
* **LIME** fits a weighted ridge model on random on/off patterns (kernel width 0.25 on cosine distance).
* **KernelSHAP** samples coalitions from the Shapley kernel and fits a linear model whose coefficients approximate Shapley values (empty and full image forced by large weights).

They are scored on the **same** NIH expert-box images as HiResCAM (pointing game, energy gain, IoU), with the time each method needs per image.
"""

try:
    from skimage.segmentation import slic
except Exception:
    slic = None
from sklearn.linear_model import Ridge, LinearRegression

def superpixels(f, n):
    # Fix: the earlier setting (compactness 0.05, no smoothing) produced ~20 regions with one region covering
    # half of the image, so LIME/SHAP gave all credit to that region. Smoothed SLIC gives ~n balanced regions.
    seg = None
    if slic is not None:
        for comp in (0.1, 0.3, 1.0):
            try:
                cand = slic(f.astype(np.float64), n_segments=n, compactness=comp, sigma=2, channel_axis=None, start_label=0)
            except Exception:
                break
            _, cnts = np.unique(cand, return_counts=True)
            if len(cnts) >= n // 2 and cnts.max() <= 0.06 * f.size:   # enough regions, none too large
                seg = cand; break
    if seg is None:   # fallback: regular grid
        g = max(2, int(round(math.sqrt(n)))); idx = np.minimum(np.arange(ISZ) * g // ISZ, g - 1)
        seg = idx[:, None] * g + idx[None, :]
    return np.unique(seg, return_inverse=True)[1].reshape(seg.shape)

@torch.no_grad()
def masked_probs(x1, seg_t, keep, cls, a, ak, bs=64):
    # returns the class LOGIT (not the probability): sigmoid saturation flattened the earlier LIME/SHAP fits
    out, xb0 = [], blurred(x1)
    for s in range(0, len(keep), bs):
        mk = torch.tensor(keep[s:s + bs], device=DEVICE, dtype=torch.float32)[:, seg_t][:, None]
        xb = x1[None] * mk + xb0[None] * (1 - mk)
        n_ = len(xb)
        with torch.autocast(device_type=DEVICE.type, dtype=torch.float16, enabled=AMP):
            lo = model(xb, a.expand(n_), ak.expand(n_))['logits'][:, cls]
        out.append(lo.float().cpu())
    return torch.cat(out).numpy()

def lime_map(x1, seg, cls, a, ak, n_samples, rng):
    S = int(seg.max()) + 1
    Z = rng.random((n_samples, S)) > 0.5; Z[0] = True
    p = masked_probs(x1, torch.tensor(seg, device=DEVICE), Z, cls, a, ak)
    d = 1 - np.sqrt(Z.sum(1) / S)                        # cosine distance to the full image
    w = np.exp(-(d ** 2) / 0.25 ** 2)
    coef = Ridge(alpha=1.0).fit(Z.astype(float), p, sample_weight=w).coef_
    return coef[seg]

def kernel_shap_map(x1, seg, cls, a, ak, n_samples, rng):
    S = int(seg.max()) + 1
    ks = np.arange(1, S); pk = (S - 1) / (ks * (S - ks)); pk = pk / pk.sum()
    sizes = rng.choice(ks, n_samples, p=pk)
    Z = np.zeros((n_samples + 2, S), bool)
    for i, k_ in enumerate(sizes):
        Z[i, rng.choice(S, k_, replace=False)] = True
    Z[-1] = True                                        # full image (row -2 stays empty)
    p = masked_probs(x1, torch.tensor(seg, device=DEVICE), Z, cls, a, ak)
    w = np.ones(len(Z)); w[-2:] = 1e6
    coef = LinearRegression().fit(Z.astype(float), p, sample_weight=w).coef_
    return coef[seg]

