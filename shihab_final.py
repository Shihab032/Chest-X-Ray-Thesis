# Image-level "abnormal" decision: one score per image = the largest margin above its own threshold
# (logit of calibrated probability minus logit of the threshold); its cut-off is fitted on validation (Youden).
def lgt(p): p = np.clip(p, 1e-6, 1 - 1e-6); return np.log(p / (1 - p))
