def fit_temperature(z, y):
    t = torch.zeros(1, requires_grad=True); zt, yt = torch.tensor(z), torch.tensor(y)
    opt = torch.optim.LBFGS([t], lr=0.1, max_iter=100)
    def clo():
        opt.zero_grad(); l = F.binary_cross_entropy_with_logits(zt / t.exp(), yt); l.backward(); return l
    opt.step(clo)
    return float(np.clip(t.exp().item(), 0.3, 5.0))

def youden_thr(y, p):
    fpr, tpr, th = roc_curve(y, p); k = np.argmax(tpr - fpr); return float(np.clip(th[k], 1e-4, 1 - 1e-4))

# Calibration groups: 0 = adult (18+), 1 = child 6-17, 2 = child 0-5, 3 = child of unknown age (all children pooled)
