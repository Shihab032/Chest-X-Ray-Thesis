"""## 4. Leakage control and splits
1. Patient overlap between official train and test lists (NIH, Kermany).
2. Near-duplicates (pHash Hamming ≤ `PHASH_MAX_HAMMING`) inside the pediatric set and **across** adult/pediatric datasets; near-duplicates are merged with a union–find into one group.
3. Splits are grouped by patient **and** duplicate group: NIH uses the official patient-wise test list as the locked test; validation is a stratified grouped fold of train-val. The pediatric official test is kept only if no group crosses it (`KERMANY_SPLIT='auto'`).
"""

def popcount64(x):
    x = x - ((x >> np.uint64(1)) & np.uint64(0x5555555555555555))
    x = (x & np.uint64(0x3333333333333333)) + ((x >> np.uint64(2)) & np.uint64(0x3333333333333333))
    x = (x + (x >> np.uint64(4))) & np.uint64(0x0F0F0F0F0F0F0F0F)
    return ((x * np.uint64(0x0101010101010101)) >> np.uint64(56)).astype(np.int32)

def near_dup_pairs(ha, hb, thr, same=False, chunk=2048):
    pairs = []
    for s in range(0, len(ha), chunk):
        d = popcount64(ha[s:s+chunk, None] ^ hb[None, :])
        i, j = np.nonzero(d <= thr); i = i + s
        if same:
            k = i < j; i, j = i[k], j[k]
        pairs.append(np.stack([i, j], 1))
    return np.concatenate(pairs) if pairs else np.zeros((0, 2), int)

_thumbs = {}
def thumb(j):
    if j not in _thumbs:
        t = cv2.resize(cv2.imread(meta.path.values[j], cv2.IMREAD_GRAYSCALE), (64, 64), interpolation=cv2.INTER_AREA).astype(np.float32).ravel()
        _thumbs[j] = (t - t.mean()) / (t.std() + 1e-6)
    return _thumbs[j]

def verify(pairs_global):
    # pHash is only a candidate filter: chest X-rays look alike at low frequency, so confirm with thumbnail correlation
    ok = [(a, b) for a, b in pairs_global if float(np.dot(thumb(a), thumb(b)) / thumb(a).size) >= CFG['DUP_MIN_CORR']]
    return np.array(ok, dtype=int).reshape(-1, 2)

class UF:
    def __init__(s, n): s.p = np.arange(n)
    def f(s, a):
        while s.p[a] != a:
            s.p[a] = s.p[s.p[a]]; a = s.p[a]
        return a
    def u(s, a, b):
        a, b = s.f(a), s.f(b)
        if a != b: s.p[b] = a

thr = CFG['PHASH_MAX_HAMMING']
H = meta.phash.values.astype(np.int64).view(np.uint64)
uf = UF(len(meta))
