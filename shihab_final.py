def preprocess(image, cfg):
    img = np.asarray(image)
    if img.ndim == 3:
        img = cv2.cvtColor(img[..., :3].astype(np.uint8), cv2.COLOR_RGB2GRAY)
    img = img.astype(np.uint8)
    if cfg.get('USE_CLAHE'):
        img = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8)).apply(img)
    s, isz = cfg['CACHE_SIZE'], cfg['IMG_SIZE']
    img = cv2.resize(img, (s, s), interpolation=cv2.INTER_AREA)
    f = cv2.resize(img, (isz, isz), interpolation=cv2.INTER_AREA).astype(np.float32) / 255.0
    x = torch.from_numpy(((np.repeat(f[None], 3, 0) - MEAN) / STD).astype(np.float32))[None]
    return x, f


def _nchw(t, nf):
    return t.permute(0, 3, 1, 2) if (t.ndim == 4 and t.shape[-1] == nf and t.shape[1] != nf) else t


def analyse(image, age=None):
    m, ck = get_model(); cfg, labels = ck['CFG'], list(ck['LABELS'])
    x, f = preprocess(image, cfg)
    if age is not None and age >= 0:
        a, ak = torch.tensor([float(age < 18)]), torch.tensor([1.0])
    else:
        a = ak = None
    m.zero_grad(set_to_none=True)
    out = m(x, a, ak, return_maps=True)
    for t in out['maps']:
        t.retain_grad()
    logits = out['logits'][0]
    ped_p = float(torch.sigmoid(out['age_logit'][0]).item()) if out['age_logit'] is not None else None
    # calibration group: 0 adult, 1 child 6-17, 2 child 0-5, 3 child of unknown age
    if age is not None and age >= 0:
        cg = 2 if age < 6 else (1 if age < 18 else 0)
    else:
        cg = 3 if (ped_p is not None and ped_p > 0.5) else 0
    TEMP_, THR_ = np.asarray(ck['TEMP']), np.asarray(ck['THR'])
    if TEMP_.shape[0] == 2:                      # older two-group bundles
        cg = 0 if cg == 0 else 1
    g = 0 if cg == 0 else 1
    lg = logits.detach().numpy()
    p = 1 / (1 + np.exp(-lg / TEMP_[cg]))
    thr = THR_[cg]
    if 'ABN_THR' in ck:
        lgt_ = lambda v: np.log(np.clip(v, 1e-6, 1 - 1e-6) / (1 - np.clip(v, 1e-6, 1 - 1e-6)))
        is_abn = bool((lgt_(p) - lgt_(thr)).max() >= np.asarray(ck['ABN_THR'])[g])
    else:
        is_abn = bool((p >= thr).any())
    c = int(np.argmax(p))
    logits[c].backward()
    isz = cfg['IMG_SIZE']; cam = np.zeros((isz, isz), np.float32); gw = out['gate'][0].detach().numpy()
    for k, (t, br) in enumerate(zip(out['maps'], m.branches)):
        A, G = _nchw(t.detach(), br.nf), _nchw(t.grad.detach(), br.nf)
        h = F.relu((A * G).sum(1))[0].numpy()
        h = cv2.resize(h, (isz, isz)); cam += gw[k] * h / (h.max() + 1e-8)
    cam = cam / (cam.max() + 1e-8)
    base = cv2.cvtColor((f * 255).astype(np.uint8), cv2.COLOR_GRAY2RGB)
    heat = cv2.cvtColor(cv2.applyColorMap((cam * 255).astype(np.uint8), cv2.COLORMAP_JET), cv2.COLOR_BGR2RGB)
    overlay = (0.6 * base + 0.4 * heat).astype(np.uint8)
    sub = None
    if out['sub_logits'] is not None and g == 1 and 'Pneumonia' in labels:
        j = labels.index('Pneumonia')
        if p[j] >= thr[j]:
            sp = torch.softmax(out['sub_logits'][0].detach(), -1).numpy()
            sub = {'bacterial': float(sp[0]), 'viral': float(sp[1])}
    age_prob = float(torch.sigmoid(out['age_logit'][0]).item()) if out['age_logit'] is not None else None
    return dict(labels=labels, prob=p, thr=thr, group='pediatric' if g == 1 else 'adult', age_prob=age_prob,
                top=labels[c], overlay=overlay, subtype=sub, abnormal=is_abn)


