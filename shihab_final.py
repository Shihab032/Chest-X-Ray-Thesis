"""## 3. Preprocess once and cache (+ perceptual hash)
Every image is read as grayscale, optionally CLAHE-equalised, and resized to a square **without letterbox padding**: black padding would appear only on the non-square pediatric images and give the model a dataset-source shortcut. A 64-bit DCT perceptual hash is computed in the same pass for near-duplicate detection.
"""

CACHE.mkdir(parents=True, exist_ok=True)
S = CFG['CACHE_SIZE']
_clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))

def phash64(img):
    small = cv2.resize(img, (32, 32), interpolation=cv2.INTER_AREA).astype(np.float32)
    d = cv2.dct(small)[:8, :8].flatten()
    bits = (d > np.median(d[1:])).astype(np.uint64)
    h = int((bits << np.arange(64, dtype=np.uint64)).sum())
    return h - (1 << 64) if h >= (1 << 63) else h   # store as signed int64

def preprocess_one(args):
    uid, src = args
    dst = CACHE / f'{uid}.jpg'
    img = cv2.imread(str(dst), cv2.IMREAD_GRAYSCALE) if dst.exists() else None
    h = w = -1
    if img is not None:
        try:
            from PIL import Image
            with Image.open(src) as im: w, h = im.size
        except Exception:
            pass
    if img is None:
        raw = cv2.imread(src, cv2.IMREAD_GRAYSCALE)
        if raw is None:
            return uid, None, -1, -1, 0
        h, w = raw.shape[:2]
        if CFG['USE_CLAHE']:
            raw = _clahe.apply(raw)
        img = cv2.resize(raw, (S, S), interpolation=cv2.INTER_AREA)
        cv2.imwrite(str(dst), img, [cv2.IMWRITE_JPEG_QUALITY, 95])
    return uid, str(dst), h, w, phash64(img)

