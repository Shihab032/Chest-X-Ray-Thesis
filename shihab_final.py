"""## 7. Model: Age-Aware Gated-Fusion Hybrid (AGF-Net)
For an image $x$ with backbones $k=1..K$ (EfficientNet-B0, MobileViTv2-1.0; about 9.5 M parameters in total):

* projected features $f_k=\mathrm{GELU}(\mathrm{LN}(W_k\,\mathrm{pool}(B_k(x))))$, sample-wise gate $w=\mathrm{softmax}(G[f_1;\dots;f_K])$, fused $z=\sum_k w_k f_k$;
* age-group head $\hat a=\sigma(h_a^\top z)$; age signal $a$ = known age group (hidden with prob. `AGE_DROP` during training) or $\hat a$;
* FiLM: $z' = z\odot(1+\gamma(a))+\beta(a)$ (last layer initialised to zero → starts as identity);
* disease logits $s(x)=W_c z' + \tau\,[(1-a)\,\mathrm{logit}\,\pi_{adult}+a\,\mathrm{logit}\,\pi_{ped}]$ (age-specific prevalence offset);
* pediatric pneumonia subtype head (bacterial / viral);
* **hospital-adversarial head** (`joint_age_adv` only): a small discriminator predicts, for children, whether the image came from NIH or Guangzhou; it sees $z$ through a **gradient-reversal layer**, so training pushes $z$ to *hide* the hospital. Its strength ramps from 0 to 1 during training (DANN schedule). It is used only during training and is not part of the deployed model.

Loss: masked, class-weighted BCE + $\lambda_{age}$ BCE(age) + $\lambda_{sub}$ CE(subtype) + $\lambda_{adv}$ BCE(hospital, through gradient reversal).
"""

class Branch(nn.Module):
    def __init__(self, name, pretrained):
        super().__init__()
        kw = {'img_size': ISZ} if (ISZ != 224 and any(k in name for k in ('swin', 'vit', 'eva'))) else {}
        self.net = timm.create_model(name, pretrained=pretrained, num_classes=0, **kw)
        self.nf = self.net.num_features
        if CFG['GRAD_CHECKPOINT']:
            try: self.net.set_grad_checkpointing(True)
            except Exception: pass
    def forward(self, x):
        f = self.net.forward_features(x)
        return f, self.net.forward_head(f, pre_logits=True)

class GradReverse(torch.autograd.Function):
    @staticmethod
    def forward(ctx, x, coef):
        ctx.coef = coef; return x.view_as(x)
    @staticmethod
    def backward(ctx, g):
        return -ctx.coef * g, None

class AGFNet(nn.Module):
    def __init__(self, names, n_labels, proj=512, dropout=0.3, film=True, age_head=True, sub_head=True,
                 logit_adj=True, prior_logit=None, pretrained=True, adv=False):
        super().__init__()
        self.branches = nn.ModuleList([Branch(n, pretrained) for n in names])
        self.projs = nn.ModuleList([nn.Sequential(nn.Linear(b.nf, proj), nn.LayerNorm(proj), nn.GELU()) for b in self.branches])
        K = len(names)
        self.gate = nn.Sequential(nn.Linear(proj * K, 256), nn.GELU(), nn.Linear(256, K)) if K > 1 else None
        self.age_head = nn.Linear(proj, 1) if age_head else None
        self.film = nn.Sequential(nn.Linear(1, 64), nn.GELU(), nn.Linear(64, 2 * proj)) if film else None
        if film:
            nn.init.zeros_(self.film[-1].weight); nn.init.zeros_(self.film[-1].bias)
        self.head = nn.Sequential(nn.LayerNorm(proj), nn.Dropout(dropout), nn.Linear(proj, n_labels))
        self.sub_head = nn.Linear(proj, 2) if sub_head else None
        # hospital discriminator: tries to tell NIH children from Guangzhou children; gradient reversal makes z hide the hospital
        self.src_head = nn.Sequential(nn.Linear(proj, 256), nn.ReLU(), nn.Dropout(0.2), nn.Linear(256, 1)) if adv else None
        self.logit_adj = logit_adj
        self.register_buffer('prior_logit', torch.tensor(prior_logit if prior_logit is not None else np.zeros((2, n_labels)), dtype=torch.float32))
        self.tau = CFG['LOGIT_ADJ_TAU']

    def backbone_params(self):
        return [p for b in self.branches for p in b.parameters()]

    def forward(self, x, age=None, age_known=None, age_drop=0.0, return_maps=False, grl=0.0):
        maps, feats = [], []
        for b, pj in zip(self.branches, self.projs):
            f, p = b(x); maps.append(f); feats.append(pj(p))
        Fs = torch.stack(feats, 1)
        w = torch.softmax(self.gate(Fs.flatten(1)), -1) if self.gate is not None else torch.ones(Fs.shape[:2], device=x.device)
        z = (w.unsqueeze(-1) * Fs).sum(1)
        age_logit = self.age_head(z).squeeze(-1) if self.age_head is not None else None
        a = None
        if self.film is not None or self.logit_adj:
            a = torch.sigmoid(age_logit).detach() if age_logit is not None else torch.full((x.shape[0],), 0.5, device=x.device)
            if age is not None:
                known = age_known > 0.5
                if self.training and age_drop > 0:
                    known = known & (torch.rand_like(age) > age_drop)
                a = torch.where(known, age.float(), a)
        zc = z
        if self.film is not None:
            g, bb = self.film(a.unsqueeze(-1)).chunk(2, -1)
            zc = z * (1 + g) + bb
        logits = self.head(zc)
        if self.logit_adj:
            logits = logits + self.tau * ((1 - a)[:, None] * self.prior_logit[0] + a[:, None] * self.prior_logit[1])
        out = dict(logits=logits, age_logit=age_logit, gate=w, z=z,
                   sub_logits=self.sub_head(zc) if self.sub_head is not None else None,
                   src_logit=self.src_head(GradReverse.apply(z, grl)).squeeze(-1) if (self.src_head is not None and self.training) else None)
        if return_maps:
            out['maps'] = maps
        return out

